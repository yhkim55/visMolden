"""Report a CASSCF result as a 16:9 PowerPoint of active-space orbitals.

Each active orbital is rendered with xyzrender from a cube file generated by
pyscf. The view is chosen so the reacting atoms (from bond_changes.json,
key "reacting_atoms" -> "idx", 0-based) are seen most distinctively:
spread out in the image plane and not hidden behind other atoms.

The atoms can instead be given directly with --atoms (0-based, same
convention as bond_changes.json), which overrides the json. With neither,
xyzrender's default (PCA) orientation is used.

Usage:
    python cas_report.py casscf.molden bond_changes.json [-o report.pptx]
    python cas_report.py casscf.molden --atoms 25,27,37,21 [-o report.pptx]
    python cas_report.py casscf.molden [-o report.pptx]
"""
import os
import sys
import json
import shutil
import logging
import argparse
import tempfile
from concurrent.futures import ProcessPoolExecutor

import numpy as np
from pyscf.tools import molden, cubegen
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN

FONT = "Arial"
FONT_SIZE = 12

log = logging.getLogger("cas_report")


# --------------------------------------------------------------------------
# Input
# --------------------------------------------------------------------------
def load_molden(molden_fn):
    mol, _, mo_coeff, mo_occ, _, _ = molden.load(molden_fn)
    return mol, mo_coeff, np.asarray(mo_occ, float)


def find_active(occ, tol=1e-4):
    """0-based indices of orbitals with fractional occupation."""
    return [i for i, n in enumerate(occ) if tol < n < 2.0 - tol]


def read_reacting_atoms(json_fn):
    with open(json_fn) as f:
        data = json.load(f)
    ra = data["reacting_atoms"]
    return list(ra["idx"]), list(ra.get("names", []))


def parse_atoms(spec, natm):
    """'25,27,37' or '21-23,25' -> list of 0-based atom indices, order kept."""
    atoms = []
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            lo, hi = part.split("-")
            atoms.extend(range(int(lo), int(hi) + 1))
        else:
            atoms.append(int(part))
    atoms = list(dict.fromkeys(atoms))  # drop duplicates
    if len(atoms) < 3:
        raise ValueError(f"--atoms needs 3 or more distinct indices, got {atoms}")
    bad = [i for i in atoms if not 0 <= i < natm]
    if bad:
        raise ValueError(f"--atoms indices out of range 0..{natm - 1}: {bad}")
    return atoms


def parse_indices(spec):
    """'15-30,35' -> sorted unique list of ints."""
    out = set()
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            lo, hi = part.split("-")
            out.update(range(int(lo), int(hi) + 1))
        else:
            out.add(int(part))
    return sorted(out)


# --------------------------------------------------------------------------
# View orientation
# --------------------------------------------------------------------------
def fibonacci_sphere(n):
    k = np.arange(n) + 0.5
    phi = np.arccos(1 - 2 * k / n)
    theta = np.pi * (1 + 5**0.5) * k
    return np.stack([np.cos(theta) * np.sin(phi),
                     np.sin(theta) * np.sin(phi),
                     np.cos(phi)], axis=1)


def view_score(d, coords, react, symbols, sigma=0.9, w_occ=0.6):
    """Score of viewing along -d (viewer sits at +d, like xyzrender's +z).

    spread: sum of projected reacting-atom pair distances / sum of 3D
            distances (1 when all pairs lie in the image plane).
    occl:   per reacting atom, Gaussian-weighted count of other atoms lying in
            front of it (closer to the viewer) and overlapping it on screen.
    """
    rc = coords[react]
    diff = rc[:, None, :] - rc[None, :, :]
    iu = np.triu_indices(len(react), 1)
    diff = diff[iu]
    full = np.linalg.norm(diff, axis=1)
    proj = np.linalg.norm(diff - np.outer(diff @ d, d), axis=1)
    spread = proj.sum() / full.sum()

    others = np.setdiff1d(np.arange(len(coords)), react)
    weight = np.array([0.5 if symbols[j] == "H" else 1.0 for j in others])
    occl = 0.0
    for i in react:
        v = coords[others] - coords[i]
        depth = v @ d
        lat = np.linalg.norm(v - np.outer(depth, d), axis=1)
        front = depth > 0.3
        occl += np.sum(weight[front] * np.exp(-(lat[front] / sigma) ** 2))
    occl /= len(react)
    return spread - w_occ * occl, spread, occl


def best_view_rotation(coords, react, symbols, ndir=4000):
    """Rotation R (apply as (x - c) @ R.T) mapping the best view direction
    onto +z, with the molecule's longest projected extent along x."""
    coords = np.asarray(coords, float)
    if len(react) < 2:
        raise ValueError("need at least two reacting atoms to define a view")

    dirs = fibonacci_sphere(ndir)
    scores = np.array([view_score(d, coords, react, symbols)[0] for d in dirs])
    d = dirs[np.argmax(scores)]
    _, spread, occl = view_score(d, coords, react, symbols)
    log.info(f"view direction {np.round(d, 3)}: spread={spread:.3f} occlusion={occl:.3f}")

    # in-plane axes: x = principal axis of the whole projected molecule
    z = d / np.linalg.norm(d)
    c = coords.mean(axis=0)
    p = (coords - c) - np.outer((coords - c) @ z, z)
    w, v = np.linalg.eigh(p.T @ p)
    x = v[:, np.argmax(w)]
    x -= (x @ z) * z
    x /= np.linalg.norm(x)
    # deterministic sign: first reacting atom on the left
    if (coords[react[0]] - coords[react].mean(axis=0)) @ x > 0:
        x = -x
    y = np.cross(z, x)
    return np.array([x, y, z])


# --------------------------------------------------------------------------
# Rendering
# --------------------------------------------------------------------------
def _write_cube(args):
    molden_fn, idx, cube_fn, res = args
    mol, mo_coeff, _ = load_molden(molden_fn)
    cubegen.orbital(mol, cube_fn, mo_coeff[:, idx], nx=res, ny=res, nz=res)
    return cube_fn


def _render(args):
    cube_fn, png_fn, R, config, iso, canvas = args
    import xyzrender

    m = xyzrender.load(cube_fn)
    if R is not None:
        nodes = list(m.graph.nodes())
        pos = np.array([m.graph.nodes[n]["position"] for n in nodes], float)
        new = (pos - pos.mean(axis=0)) @ R.T
        for n, p in zip(nodes, new):
            m.graph.nodes[n]["position"] = tuple(float(t) for t in p)
        # cube lobes follow via xyzrender's Kabsch alignment of cube atoms -> graph
        m.oriented = True
    # R is None: xyzrender's PCA auto-orientation (same atoms -> same view)
    xyzrender.render(m, config=config, mo=True, hy=True, orient=R is None,
                     iso=iso, canvas_size=canvas, output=png_fn)
    return png_fn


def crop_common(png_fns, pad=10):
    """Crop all PNGs to the union bounding box of non-white pixels so every
    image keeps the same scale and framing."""
    from PIL import Image, ImageChops

    box = None
    for fn in png_fns:
        im = Image.open(fn).convert("RGB")
        bg = Image.new("RGB", im.size, (255, 255, 255))
        bb = ImageChops.difference(im, bg).getbbox()
        if bb is None:
            continue
        box = bb if box is None else (min(box[0], bb[0]), min(box[1], bb[1]),
                                      max(box[2], bb[2]), max(box[3], bb[3]))
    if box is None:
        return
    for fn in png_fns:
        im = Image.open(fn)
        b = (max(box[0] - pad, 0), max(box[1] - pad, 0),
             min(box[2] + pad, im.width), min(box[3] + pad, im.height))
        im.crop(b).save(fn)


# --------------------------------------------------------------------------
# PowerPoint
# --------------------------------------------------------------------------
def add_text(slide, left, top, width, height, text, size=FONT_SIZE, bold=False,
             align=PP_ALIGN.CENTER):
    box = slide.shapes.add_textbox(left, top, width, height)
    tf = box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = align
    run = p.add_run()
    run.text = text
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = RGBColor(0, 0, 0)


def format_ranges(indices):
    """[67, 68, 69, 72] -> '67-69, 72'"""
    out, start, prev = [], None, None
    for i in sorted(indices):
        if start is None:
            start = prev = i
        elif i == prev + 1:
            prev = i
        else:
            out.append(f"{start}-{prev}" if prev > start else f"{start}")
            start = prev = i
    if start is not None:
        out.append(f"{start}-{prev}" if prev > start else f"{start}")
    return ", ".join(out)


def build_pptx(png_map, occ, orb_indices, title, ppt_fn, ncol=8, nrow=None,
               one_based=False):
    """Images are laid out in reading order, left to right then top to bottom."""
    from PIL import Image

    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    layout = prs.slide_layouts[6]  # blank

    margin_x, margin_top, margin_bot = Inches(0.3), Inches(1.15), Inches(0.2)
    gap_x, gap_y, txt_h = Inches(0.08), Inches(0.1), Inches(0.3)
    cell_w = (prs.slide_width - 2 * margin_x - (ncol - 1) * gap_x) // ncol
    # images share a common crop, so one aspect ratio fixes the row height
    aspect = max(h / w for w, h in (Image.open(f).size for f in png_map.values()))
    avail_h = prs.slide_height - margin_top - margin_bot
    img_box_h = int(cell_w * aspect)
    if nrow is None:
        nrow = max(1, (avail_h + gap_y) // (img_box_h + txt_h + gap_y))
    img_box_h = min(img_box_h, (avail_h + gap_y) // nrow - txt_h - gap_y)
    cell_h = img_box_h + txt_h + gap_y
    per_slide = ncol * nrow

    for start in range(0, len(orb_indices), per_slide):
        slide = prs.slides.add_slide(layout)
        subset = orb_indices[start:start + per_slide]
        add_text(slide, Inches(0.3), Inches(0.2), prs.slide_width - Inches(0.6),
                 Inches(0.5), title, size=18, bold=True, align=PP_ALIGN.LEFT)
        labels = [i + 1 if one_based else i for i in subset]
        add_text(slide, Inches(0.3), Inches(0.65), prs.slide_width - Inches(0.6),
                 Inches(0.4), f"Orbital index: {format_ranges(labels)}",
                 size=14, align=PP_ALIGN.LEFT)

        for k, idx in enumerate(subset):
            row, col = divmod(k, ncol)
            left = margin_x + col * (cell_w + gap_x)
            top = margin_top + row * cell_h

            w_px, h_px = Image.open(png_map[idx]).size
            scale = min(cell_w / w_px, img_box_h / h_px)
            w, h = int(w_px * scale), int(h_px * scale)
            slide.shapes.add_picture(png_map[idx], left + (cell_w - w) // 2,
                                     top + (img_box_h - h), width=w, height=h)

            add_text(slide, left, top + img_box_h, cell_w, txt_h,
                     f"Occ={occ[idx]:.3f}")

    prs.save(ppt_fn)


# --------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("molden", help="CASSCF molden file (natural orbitals)")
    ap.add_argument("bond_changes", nargs="?", default=None,
                    help="bond_changes.json (optional; without it and --atoms, "
                         "xyzrender's default orientation is used)")
    ap.add_argument("--atoms", default=None,
                    help='3 or more 0-based atom indices, e.g. "25,27,37" or "21-23,25"; '
                         'overrides "reacting_atoms" in bond_changes.json')
    ap.add_argument("-o", "--output", default=None,
                    help="output pptx (default: <molden>_cas_report.pptx)")
    ap.add_argument("--orbitals", default=None,
                    help='0-based orbital indices, e.g. "89-96" '
                         "(default: fractionally occupied orbitals)")
    ap.add_argument("--one-based", action="store_true",
                    help="print 1-based orbital indices on slides (default 0-based)")
    ap.add_argument("--iso", type=float, default=None, help="isovalue (xyzrender default 0.05)")
    ap.add_argument("--res", type=int, default=80, help="cube grid points per axis")
    ap.add_argument("--config", default="paton", help="xyzrender config preset")
    ap.add_argument("--canvas", type=int, default=None, help="xyzrender canvas size (px)")
    ap.add_argument("--workdir", default=None, help="keep cube/png files here")
    ap.add_argument("--title", default=None, help="slide title")
    args = ap.parse_args()

    logging.basicConfig(level=logging.INFO, stream=sys.stdout,
                        format="%(asctime)s - %(levelname)s - %(message)s")

    molden_fn = os.path.abspath(args.molden)
    output = args.output or os.path.splitext(molden_fn)[0] + "_cas_report.pptx"

    mol, _, occ = load_molden(molden_fn)
    orbs = parse_indices(args.orbitals) if args.orbitals else find_active(occ)
    if not orbs:
        raise RuntimeError("no active orbitals found; pass --orbitals")
    nelec = occ[orbs].sum()
    log.info(f"active orbitals {orbs[0]}..{orbs[-1]} ({len(orbs)}), {nelec:.2f} e")

    symbols = [mol.atom_pure_symbol(i) for i in range(mol.natm)]
    if args.atoms is not None:
        react, names = parse_atoms(args.atoms, mol.natm), []
    elif args.bond_changes is not None:
        react, names = read_reacting_atoms(args.bond_changes)
    else:
        react, names = None, []

    if react is None:
        log.info("no reacting atoms given; using xyzrender default orientation")
        R = None
    else:
        if not names:
            names = [f"{symbols[i]}{i + 1}" for i in react]
        log.info(f"reacting atoms: {', '.join(names)} (0-based {react})")
        R = best_view_rotation(mol.atom_coords(unit="Angstrom"), react, symbols)

    title = args.title or f"CAS({round(nelec)}e, {len(orbs)}o) {molden_fn}"

    workdir = os.path.abspath(args.workdir) if args.workdir else tempfile.mkdtemp(prefix="cas_report_")
    os.makedirs(workdir, exist_ok=True)
    try:
        nproc = int(os.environ.get("SLURM_CPUS_PER_TASK", min(os.cpu_count() or 1, 8)))
        cubes = [os.path.join(workdir, f"orb{i:04d}.cube") for i in orbs]
        pngs = [c.replace(".cube", ".png") for c in cubes]

        log.info(f"generating {len(cubes)} cube files ({nproc} workers)")
        with ProcessPoolExecutor(max_workers=nproc) as ex:
            list(ex.map(_write_cube, [(molden_fn, i, c, args.res) for i, c in zip(orbs, cubes)]))

        log.info("rendering with xyzrender")
        with ProcessPoolExecutor(max_workers=nproc) as ex:
            list(ex.map(_render, [(c, p, R, args.config, args.iso, args.canvas)
                                  for c, p in zip(cubes, pngs)]))
        crop_common(pngs)

        build_pptx(dict(zip(orbs, pngs)), occ, orbs, title, output,
                   one_based=args.one_based)
        log.info(f"saved {output}")
    finally:
        if not args.workdir:
            shutil.rmtree(workdir, ignore_errors=True)


if __name__ == "__main__":
    main()
